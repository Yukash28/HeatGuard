import pytest

from wbgt import calculate_wbgt


# Fixed reference conditions (Bengaluru coordinates, matching wbgt.py's
# hardcoded LATITUDE/LONGITUDE) so tests are reproducible.

def test_wbgt_midday_hot_sunny():
    """
    Midday, clear sky, hot and moderately humid, decent wind.
    Note: with strong direct sun, WBGT can exceed air temp — the black
    globe term captures radiant heating that a shaded air-temp reading
    doesn't. 36.45°C against 35°C air temp is physically expected here,
    not a bug.
    """
    EXPECTED = 36.45

    result = calculate_wbgt(
        temperature_c=35.0,
        humidity=55,
        wind_kmh=10.0,
        radiation=850,
        pressure_hpa=1005,
        direct_radiation=700,
        timestamp="2026-06-15T13:00",
    )

    if EXPECTED is None:
        pytest.fail(f"Fill in EXPECTED = {result} for this scenario")
    assert result == pytest.approx(EXPECTED, abs=0.3)


