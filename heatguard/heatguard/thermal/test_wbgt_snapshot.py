# --- Directional sanity checks (no exact values needed) -------------------

def test_wbgt_increases_with_humidity():
    """Holding everything else fixed, higher humidity should raise WBGT."""
    low_humidity = calculate_wbgt(
        temperature_c=32.0, humidity=30, wind_kmh=8.0, radiation=600,
        pressure_hpa=1005, direct_radiation=450, timestamp="2026-06-15T12:00",
    )
    high_humidity = calculate_wbgt(
        temperature_c=32.0, humidity=85, wind_kmh=8.0, radiation=600,
        pressure_hpa=1005, direct_radiation=450, timestamp="2026-06-15T12:00",
    )
    assert high_humidity > low_humidity


def test_wbgt_decreases_with_wind():
    """Holding everything else fixed, more wind should lower WBGT."""
    calm = calculate_wbgt(
        temperature_c=32.0, humidity=60, wind_kmh=2.0, radiation=600,
        pressure_hpa=1005, direct_radiation=450, timestamp="2026-06-15T12:00",
    )
    windy = calculate_wbgt(
        temperature_c=32.0, humidity=60, wind_kmh=20.0, radiation=600,
        pressure_hpa=1005, direct_radiation=450, timestamp="2026-06-15T12:00",
    )
    assert windy < calm


def test_wbgt_stays_within_plausible_range_of_air_temp():
    """
    WBGT should stay within a physically plausible band of air temp — not
    equal to it (that would mean humidity/wind/radiation aren't being
    applied at all), but not wildly divergent either. Note strong direct
    sun CAN push WBGT above air temp (see test_wbgt_midday_hot_sunny) —
    that's the black globe term capturing radiant heat, not a bug.
    """
    result = calculate_wbgt(
        temperature_c=35.0, humidity=60, wind_kmh=10.0, radiation=700,
        pressure_hpa=1005, direct_radiation=550, timestamp="2026-06-15T13:00",
    )
    assert result != 35.0
    assert 25.0 < result < 45.0
